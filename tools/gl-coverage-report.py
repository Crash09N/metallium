"""Renders docs/compat/gl-coverage.md from GlCoverageScan JSON (./gradlew :metallium-gl:glCoverage).

usage: gl-coverage-report.py [--manifest manifest.json] [--summary] out.md scan.json[:label] ...

Each scan file is one corpus (e.g. the Modrinth top list and an owner instance). Mods present in several corpora
(same mod id) are counted once in the combined numbers. Only the part between the generated markers of out.md is
replaced, so hand-written text around it is kept.
"""
import json
import sys
from collections import Counter, defaultdict

BEGIN, END = "<!-- gl-coverage:begin (generated by tools/gl-coverage-report.py) -->", "<!-- gl-coverage:end -->"


def category(m):
    if m.get("error") and not m.get("classes"):
        return "error"
    if m["backendUnhandled"]:
        return "mc-gl-backend"
    if m["rawGlClasses"] == 0 and not m["backendHandledUnrouted"]:
        return "native"
    if m["backendHandledUnrouted"]:
        return "mc-gl-backend"
    if m["missing"] or m["methodReferences"]:
        return "raw-gl-partial"
    return "raw-gl-covered"


def load(args):
    corpora = []
    for a in args:
        path, _, label = a.partition(":")
        corpora.append((label or path, json.load(open(path))))
    return corpora


def fn_name(key):
    return key.split("(")[0]


def main():
    argv = sys.argv[1:]
    manifest = {}
    if argv and argv[0] == "--manifest":
        for e in json.load(open(argv[1])):
            if "file" in e:
                manifest[e["file"]] = e
        argv = argv[2:]
    summary_only = bool(argv) and argv[0] == "--summary"
    if summary_only:
        argv = argv[1:]
    out, scans = argv[0], argv[1:]
    corpora = load(scans)

    lines = []
    seen = {}
    per_corpus = []
    for label, mods in corpora:
        counts = Counter(category(m) for m in mods)
        per_corpus.append((label, len(mods), counts))
        for m in mods:
            seen.setdefault(m.get("id") or m["file"], m)
    allmods = list(seen.values())
    total = Counter(category(m) for m in allmods)

    def pct(c, n):
        return f"{100.0 * c / n:.1f} %" if n else "-"

    lines.append("| Corpus | Mods | Native | Raw GL, fully translated | Raw GL, gaps | Minecraft GL backend | Covered (native + translated) | Covered, excluding MC-GL-backend mods |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for label, n, c in per_corpus + [("**combined (unique mod ids)**", len(allmods), total)]:
        ok = c["native"] + c["raw-gl-covered"]
        lines.append(f"| {label} | {n} | {c['native']} | {c['raw-gl-covered']} | {c['raw-gl-partial']} | {c['mc-gl-backend']} | "
                     f"{ok} = {pct(ok, n)} | {pct(ok, n - c['mc-gl-backend'])} |")
    lines.append("")

    # Missing functions ranked by mods needing them.
    need = defaultdict(set)
    for m in allmods:
        for f in m["missing"]:
            need[fn_name(f)].add(m.get("id") or m["file"])
        for f in m["methodReferences"]:
            need["method reference " + f].add(m.get("id") or m["file"])
    lines.append("### Missing GL functions, ranked by number of mods (combined corpus)")
    lines.append("")
    if need:
        lines.append("| Function | Mods | Which |")
        lines.append("|---|---|---|")
        for f, ids in sorted(need.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            lines.append(f"| `{f}` | {len(ids)} | {', '.join(sorted(ids))} |")
    else:
        lines.append("None: every GL call site of every raw-GL class in the corpus has a metallium-gl implementation.")
    lines.append("")

    # Most used GL functions (all implemented ones too), for context.
    used = defaultdict(set)
    for m in allmods:
        if category(m) in ("raw-gl-covered", "raw-gl-partial"):
            for f in m["functions"]:
                used[fn_name(f)].add(m.get("id") or m["file"])
    lines.append("### Raw-GL mods (combined corpus)")
    lines.append("")
    lines.append("| Mod | Version | Licence | Category | Raw-GL classes | Call sites | GL functions | Missing | Handled MC-backend refs |")
    lines.append("|---|---|---|---|---|---|---|---|---|")
    for m in sorted(allmods, key=lambda m: (category(m), m.get("id") or "")):
        cat = category(m)
        if cat in ("native", "mc-gl-backend"):
            continue
        fns = sorted({fn_name(f) for f in m["functions"]})
        lines.append(f"| {m.get('name') or m['file']} (`{m.get('id')}`) | {m.get('version')} | {m.get('license') or '?'} | {cat} | "
                     f"{m['rawGlClasses']} | {m['callSites']} | {len(fns)} | {', '.join('`' + fn_name(f) + '`' for f in m['missing']) or '-'} | "
                     f"{len(m['backendHandled'])} |")
    lines.append("")
    lines.append("### Mods using Minecraft's OpenGL backend internals (separate category, not translated)")
    lines.append("")
    lines.append("| Mod | Version | Also raw GL | Classes | Examples |")
    lines.append("|---|---|---|---|---|")
    for m in sorted(allmods, key=lambda m: m.get("id") or ""):
        if category(m) != "mc-gl-backend":
            continue
        refs = sorted({r for v in m["backendUnhandled"].values() for r in v} | set(m["backendHandledUnrouted"]))
        lines.append(f"| {m.get('name') or m['file']} (`{m.get('id')}`) | {m.get('version')} | {'yes' if m['rawGlClasses'] else 'no'} | "
                     f"{len(m['backendUnhandled']) or len(m['backendHandledUnrouted'])} | {', '.join('`' + r + '`' for r in refs[:6])}{' ...' if len(refs) > 6 else ''} |")
    lines.append("")
    lines.append("### GL functions used by raw-GL mods (combined corpus, top 60)")
    lines.append("")
    lines.append("| Function | Mods |")
    lines.append("|---|---|")
    for f, ids in sorted(used.items(), key=lambda kv: (-len(kv[1]), kv[0]))[:60]:
        lines.append(f"| `{f}` | {len(ids)} |")
    lines.append("")
    lines.append("### Native mods")
    lines.append("")
    lines.append(", ".join(sorted(f"`{m.get('id') or m['file']}`" for m in allmods if category(m) == "native")))
    lines.append("")
    errors = [m for m in allmods if category(m) == "error"]
    if errors:
        lines.append("Not scannable: " + ", ".join(f"{m['file']} ({m['error']})" for m in errors))
        lines.append("")

    text = "\n".join(lines)
    if summary_only:
        print("\n".join(lines[:2 + len(per_corpus) + 1]))
        print("\n".join(l for l in lines if l.startswith("| `") and "|" in l)[:6000])
        return
    try:
        doc = open(out).read()
    except FileNotFoundError:
        doc = f"{BEGIN}\n{END}\n"
    head, _, rest = doc.partition(BEGIN)
    _, _, tail = rest.partition(END)
    open(out, "w").write(f"{head}{BEGIN}\n{text}\n{END}{tail}")


if __name__ == "__main__":
    main()
